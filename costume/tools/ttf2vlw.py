#!/usr/bin/env python3
"""Convert a TTF to a LovyanGFX/TFT_eSPI "VLW" smooth font, as a C header.

VLW layout (all integers 32-bit big-endian):
  header : glyph count, version (11), font size, 0, ascent, descent
  table  : per glyph -- unicode, height, width, xAdvance, dY (top of bitmap
           above the baseline), dX (left offset), 0
  bitmaps: per glyph, width*height bytes of 8-bit alpha, in table order

LovyanGFX stores width and xAdvance as uint8, so glyphs must stay under
256 px wide. Only printable ASCII is converted: keep messages.h ASCII.

Usage: ttf2vlw.py <font.ttf> <size_px> <c_symbol> <out.h>
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont


def convert(ttf, size, symbol, out_path):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    chars = [chr(c) for c in range(0x20, 0x7F)]

    table = bytearray()
    bitmaps = bytearray()
    for ch in chars:
        advance = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if ch == " " or w == 0 or h == 0:
            w = h = 0
            x0 = y0 = 0
        else:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bitmaps += img.tobytes()
        if w > 255 or advance > 255:
            sys.exit(f"{ch!r} is {w}px wide / {advance}px advance; LovyanGFX's VLW limit is 255")
        table += struct.pack(">7i", ord(ch), h, w, advance, -y0, x0, 0)

    data = struct.pack(">6i", len(chars), 11, size, 0, ascent, descent) + table + bitmaps

    with open(out_path, "w") as f:
        f.write(f"// Generated by tools/ttf2vlw.py from {ttf.split('/')[-1]} at {size}px -- do not edit.\n")
        f.write("// JetBrains Mono: SIL Open Font License 1.1 (fonts_src/OFL.txt).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"static const uint8_t {symbol}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"{out_path}: {len(data)} bytes, advance {int(round(font.getlength('M')))}px, "
          f"line {ascent + descent}px")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    convert(sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4])
