#!/usr/bin/env python3
"""Record the robot voice clips for every list in src/messages.h marked "// @voice".

Uses macOS `say` (voice Zarvox) and ffmpeg (a little echo and bit-crush for
grit), then stores each line as 8-bit mu-law at 16 kHz in
src/voice/voice_clips.h. The firmware matches clips by their exact text, so
re-run this after editing any @voice text:

    python3 tools/make_voice.py            # all clips
    python3 tools/make_voice.py --voice Trinoids --rate 170
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MESSAGES = os.path.join(ROOT, "src", "messages.h")
OUT = os.path.join(ROOT, "src", "voice", "voice_clips.h")
RATE = 16000

# Words the speech engine gets wrong, as they should be spoken.
SAY_AS = {
    "AI": "A.I.",
    "ROGUE.AI": "rogue A.I.",
    "sudo rm -rf": "sudo, remove, recursive, force,",
    "404:": "four oh four.",
    "1997": "nineteen ninety seven",
}

FILTER = ("silenceremove=start_periods=1:start_threshold=-45dB,"
          "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
          "aecho=0.8:0.5:28:0.25,acrusher=bits=9:mix=0.25,"
          "highpass=f=180,lowpass=f=6500,loudnorm=I=-14:TP=-1.5")


def literals_after_tags(src):
    """Yield the string literals of each declaration following a // @voice line."""
    lines = src.splitlines()
    for i, line in enumerate(lines):
        if line.strip() != "// @voice":
            continue
        decl = []
        for j in range(i + 1, len(lines)):
            decl.append(lines[j])
            if lines[j].rstrip().endswith(";"):
                break
        body = "\n".join(decl)
        body = body.split("=", 1)[1]
        for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', body):
            yield lit


def unescape(lit):
    return bytes(lit, "utf-8").decode("unicode_escape")


def spoken(text):
    t = text.replace("\n", " ")
    for k, v in SAY_AS.items():
        t = t.replace(k, v)
    return t


def mulaw(sample):
    BIAS, CLIP = 0x84, 32635
    sign = 0x80 if sample < 0 else 0
    s = min(abs(sample), CLIP) + BIAS
    exp = 7
    mask = 0x4000
    while exp > 0 and not (s & mask):
        exp -= 1
        mask >>= 1
    mant = (s >> (exp + 3)) & 0x0F
    return ~(sign | (exp << 4) | mant) & 0xFF


def record(text, voice, rate, tmp):
    aiff = os.path.join(tmp, "a.aiff")
    raw = os.path.join(tmp, "a.raw")
    subprocess.run(["say", "-v", voice, "-r", str(rate), "-o", aiff, spoken(text)], check=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", aiff, "-af", FILTER,
                    "-ar", str(RATE), "-ac", "1", "-f", "s16le", raw], check=True)
    pcm = open(raw, "rb").read()
    samples = [int.from_bytes(pcm[k:k + 2], "little", signed=True) for k in range(0, len(pcm) - 1, 2)]
    return bytes(mulaw(s) for s in samples)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="Zarvox")
    ap.add_argument("--rate", type=int, default=165, help="words per minute")
    args = ap.parse_args()

    src = open(MESSAGES, encoding="utf-8").read()
    lits = []
    for lit in literals_after_tags(src):
        if lit not in lits:
            lits.append(lit)

    clips = []
    total = 0
    with tempfile.TemporaryDirectory() as tmp:
        for lit in lits:
            data = record(unescape(lit), args.voice, args.rate, tmp)
            clips.append((lit, data))
            total += len(data)
            print(f"{len(data) / RATE:5.2f}s  {unescape(lit)!r}")

    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_voice.py -- do not edit. Re-run after changing @voice text.\n")
        f.write(f"// Voice: {args.voice} at {args.rate} wpm; {len(clips)} clips, {total} bytes.\n")
        f.write('#pragma once\n#include "voice_types.h"\n\n')
        for n, (_, data) in enumerate(clips):
            f.write(f"static const uint8_t VOICE_DATA_{n}[{len(data)}] = {{\n")
            for k in range(0, len(data), 32):
                f.write("  " + ",".join(str(b) for b in data[k:k + 32]) + ",\n")
            f.write("};\n")
        f.write(f"\nstatic const VoiceClip VOICE_CLIPS[{len(clips)}] = {{\n")
        for n, (lit, data) in enumerate(clips):
            f.write(f'  {{"{lit}", VOICE_DATA_{n}, {len(data)}}},\n')
        f.write("};\n")
        f.write(f"static const int VOICE_CLIP_COUNT = {len(clips)};\n")
    print(f"{len(clips)} clips, {total / 1024:.0f} KB -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
